import os from "node:os";

console.log(os.arch()); //conocer la arquitectura del sistema operativo
console.log(os.freemem()); //conocer la cantidad de memoria libre
console.log(os.totalmem()); //conocer la cantidad de memoria total
console.log(os.hostname()); //conocer el nombre del host
console.log(os.cpus()); //conocer la información de los procesadores
console.log(os.homedir()); //conocer el directorio del usuario
console.log(os.uptime()); //conocer el tiempo de actividad del sistema
